// Save the public demo (the stored run, its report and the featured experiments) as lib/demo-snapshot.ts, so the
// /demo page can show it at once when the API is asleep or slow. Run it again after the demo data changes:
//
//   node scripts/snapshot-demo.mjs https://<your-api>
//
// It reads the public route only: nothing in it is private.
import { writeFileSync } from "node:fs";

const api = (process.argv[2] ?? process.env.NEXT_PUBLIC_API_URL ?? "").replace(/\/$/, "");
if (!api) {
  console.error("Give the API address: node scripts/snapshot-demo.mjs https://<your-api>");
  process.exit(1);
}
const res = await fetch(`${api}/v1/public/demo`, { signal: AbortSignal.timeout(120000) });
if (!res.ok) {
  console.error(`The API answered ${res.status}`);
  process.exit(1);
}
const demo = await res.json();
if (!demo?.run?.steps?.length) {
  console.error("The answer has no run in it: is the demo seeded on that server?");
  process.exit(1);
}
const out = new URL("../lib/demo-snapshot.ts", import.meta.url);
writeFileSync(
  out,
  `// Generated by scripts/snapshot-demo.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.\n` +
    `// The saved demo exactly as the API stored it, shown at once if the API is asleep or slow.\n` +
    `export const demoSnapshot: unknown = ${JSON.stringify(demo, null, 1)};\n`,
);
console.log(`Saved the demo: ${demo.run.steps.length} steps, ${demo.experiments.length} experiments, report ${demo.rca ? "yes" : "no"}`);
